INSERT INTO upload_history(upload_id,uploaded_at,uploader_name,operator_name,source_json)
 SELECT u.id,u.created_at,u.uploader_name,u.operator_name,
 jsonb_build_object('original_upload_id',u.id,'csv_path',u.csv_path,'sha256',u.sha256,'columns',u.columns_json)
 FROM uploads u WHERE NOT EXISTS (SELECT 1 FROM upload_history h WHERE h.upload_id=u.id);
-- Consolidate old same-name batches, preserving every remaining detail and event.
CREATE TEMP TABLE upload_merge ON COMMIT DROP AS
 SELECT id,first_value(id) OVER (PARTITION BY user_id,original_name COLLATE "C",sheet_name COLLATE "C" ORDER BY updated_at DESC,id DESC) AS target,
 count(*) OVER (PARTITION BY user_id,original_name COLLATE "C",sheet_name COLLATE "C") AS copies FROM uploads;
UPDATE uploads u SET columns_json=merged.columns FROM (
 SELECT target,jsonb_agg(name ORDER BY first_order) AS columns FROM (
 SELECT target,name,MIN(ord) first_order FROM (
 SELECT m.target,c.name,row_number() OVER (PARTITION BY m.target ORDER BY b.updated_at DESC,b.id DESC,c.n) ord
 FROM upload_merge m JOIN uploads b ON b.id=m.id
 CROSS JOIN LATERAL jsonb_array_elements_text(b.columns_json) WITH ORDINALITY c(name,n) WHERE m.copies>1
 ) ordered GROUP BY target,name) names GROUP BY target
) merged WHERE u.id=merged.target;
UPDATE settlement_rows r SET upload_id=m.target FROM upload_merge m WHERE r.upload_id=m.id AND m.id<>m.target;
UPDATE upload_history h SET upload_id=m.target FROM upload_merge m WHERE h.upload_id=m.id AND m.id<>m.target;
UPDATE uploads u SET created_at=(SELECT MIN(uploaded_at) FROM upload_history WHERE upload_id=u.id),
 row_count=(SELECT COUNT(*) FROM settlement_rows WHERE upload_id=u.id),
 total_amount=(SELECT COALESCE(SUM(amount),0) FROM settlement_rows WHERE upload_id=u.id),
 date_from=(SELECT MIN(settlement_date) FROM settlement_rows WHERE upload_id=u.id),
 date_to=(SELECT MAX(settlement_date) FROM settlement_rows WHERE upload_id=u.id)
 WHERE u.id IN (SELECT target FROM upload_merge WHERE copies>1);
DELETE FROM uploads u USING upload_merge m WHERE u.id=m.id AND m.id<>m.target;
