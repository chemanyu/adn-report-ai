CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identity_key VARCHAR(191) COLLATE "C" NOT NULL UNIQUE,
 name VARCHAR(191) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_login_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS oauth_states (
 token_hash CHAR(64) PRIMARY KEY,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS uploads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,
 uploader_name VARCHAR(191) NOT NULL,
 operator_name VARCHAR(191) NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 sheet_name VARCHAR(191) NOT NULL,
 sha256 CHAR(64) NOT NULL,
 csv_path VARCHAR(255) NOT NULL,
 columns_json JSONB NOT NULL,
 row_count INT NOT NULL,
 total_amount DECIMAL(30,6) NOT NULL,
 date_from DATE,
 date_to DATE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
